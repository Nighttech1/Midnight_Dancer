import XCTest
import CryptoKit
import Darwin
@testable import MidnightDancer

final class MdanceV1CodecTests: XCTestCase {
    private var root: URL!
    private var codec: MdanceV1Codec!
    private let bundle = "com.midnightdancer.app"
    override func setUpWithError() throws {
        root = FileManager.default.temporaryDirectory.appendingPathComponent("mdance-codec-test-\(UUID().uuidString)", isDirectory: true)
        try FileManager.default.createDirectory(at: root, withIntermediateDirectories: false)
        codec = MdanceV1Codec(privateRoot: root)
    }
    override func tearDownWithError() throws { if let root { try FileManager.default.removeItem(at: root) } }
    private func file(_ name: String, _ bytes: Data) throws -> URL {
        let path = root.appendingPathComponent(name); try bytes.write(to: path); return path
    }
    private func temporaryFiles() throws -> [URL] {
        try FileManager.default.contentsOfDirectory(at: root, includingPropertiesForKeys: nil).filter { $0.lastPathComponent.hasPrefix(".mdance-") }
    }
    private func key(_ bundle: String) -> SymmetricKey {
        SymmetricKey(data: SHA256.hash(data: Data((bundle + "MD-N1ght" + "Dancer#9").utf8)))
    }
    private func cryptoKitWire(_ clear: Data, bundle: String) throws -> Data {
        let nonce = try AES.GCM.Nonce(data: Data((0..<12).map(UInt8.init)))
        let sealed = try AES.GCM.seal(clear, using: key(bundle), nonce: nonce)
        return Data("MDANCE1".utf8) + Data([1]) + Data(nonce) + sealed.ciphertext + sealed.tag
    }

    func testAndroidV1JcaGoldenDecryptsWithExactHeaderAndPartialBlock() throws {
        // Generated by real JDK17 javax.crypto.Cipher AES/GCM/NoPadding, following Android v1 reference.
        // Independently opened with Python cryptography during fixture creation; no external/private data.
        let wire = Data(base64Encoded: "TURBTkNFMQEAAQIDBAUGBwgJCgsl3SwFgC3zHywedTx+Jvw6i4Ug8Q6numbxxJ/wYZQUk6UWpQ0A2DyZDGSEf+xIIYBIUuV0AaPP9lIhKSvtNPNRL/Vf5FdtWI7MDzg4AC5STZe5pbcaNboL8gfJugeUuUSyShTNOB+yeGVgjBNvNF0AZw==")!
        let source = try file("android-reference.dance", wire)
        let destination = root.appendingPathComponent("verified.zip")
        try codec.decrypt(container: source, destination: destination, bundleId: bundle)
        XCTAssertEqual(try Data(contentsOf: destination), Data((0..<97).map { UInt8(truncatingIfNeeded: $0 * 31) }))
        XCTAssertEqual(wire.count, 97 + 36)
        XCTAssertTrue(try temporaryFiles().isEmpty)
    }

    func testStreamingEncryptOpensWithIndependentCryptoKit() throws {
        let clear = Data((0..<131073).map { UInt8(truncatingIfNeeded: $0 * 17) })
        let source = try file("input.zip", clear); let destination = root.appendingPathComponent("encrypted.dance")
        try codec.encrypt(zip: source, destination: destination, bundleId: bundle)
        let wire = try Data(contentsOf: destination)
        XCTAssertEqual(wire.count, clear.count + 36)
        XCTAssertEqual(wire.prefix(8), Data("MDANCE1".utf8) + Data([1]))
        let box = try AES.GCM.SealedBox(nonce: AES.GCM.Nonce(data: wire.subdata(in: 8..<20)),
                                        ciphertext: wire.subdata(in: 20..<wire.count - 16), tag: wire.suffix(16))
        XCTAssertEqual(try AES.GCM.open(box, using: key(bundle)), clear)
    }

    func testIndependentCryptoKitCiphertextOpensWithStreamingDecoder() throws {
        let clear = Data((0..<65539).map { UInt8(truncatingIfNeeded: $0 * 13) })
        let source = try file("cryptokit.dance", cryptoKitWire(clear, bundle: bundle))
        let destination = root.appendingPathComponent("verified.zip")
        try codec.decrypt(container: source, destination: destination, bundleId: bundle)
        XCTAssertEqual(try Data(contentsOf: destination), clear)
    }

    func testWrongTagCiphertextIvVersionTruncationAppendAndBundlePreservePreviousOutput() throws {
        let valid = try cryptoKitWire(Data(repeating: 0x35, count: 8193), bundle: bundle)
        var cases = [Data]()
        for position in [7, 8, 21, valid.count - 1] {
            var changed = valid; changed[position] ^= 1; cases.append(changed)
        }
        cases.append(Data(valid.dropLast())); cases.append(valid + Data([0]))
        let sentinel = Data("previous-verified-output".utf8)
        let destination = try file("verified.zip", sentinel)
        for (index, changed) in cases.enumerated() {
            let source = try file("bad-\(index).dance", changed)
            XCTAssertThrowsError(try codec.decrypt(container: source, destination: destination, bundleId: bundle))
            XCTAssertEqual(try Data(contentsOf: destination), sentinel)
            XCTAssertTrue(try temporaryFiles().isEmpty)
        }
        let source = try file("wrong-bundle.dance", valid)
        XCTAssertThrowsError(try codec.decrypt(container: source, destination: destination, bundleId: bundle + ".different"))
        XCTAssertEqual(try Data(contentsOf: destination), sentinel)
    }

    func testCancellationAfterPartialIoPreservesOutputAndRemovesOnlyOwnedTemporary() throws {
        let clear = Data(repeating: 0x47, count: 200000)
        let source = try file("input.zip", clear); let destination = try file("out.dance", Data([1, 2, 3]))
        var checks = 0
        XCTAssertThrowsError(try codec.encrypt(zip: source, destination: destination, bundleId: bundle, shouldCancel: { checks += 1; return checks >= 4 }))
        XCTAssertEqual(try Data(contentsOf: destination), Data([1, 2, 3]))
        XCTAssertEqual(try Data(contentsOf: source), clear)
        XCTAssertTrue(try temporaryFiles().isEmpty)
        let encrypted = try file("good.dance", cryptoKitWire(clear, bundle: bundle))
        checks = 0
        XCTAssertThrowsError(try codec.decrypt(container: encrypted, destination: destination, bundleId: bundle, shouldCancel: { checks += 1; return checks >= 4 }))
        XCTAssertEqual(try Data(contentsOf: destination), Data([1, 2, 3]))
        XCTAssertTrue(try temporaryFiles().isEmpty)
    }

    func testPlaintextNeverPublishedBeforeFinalTagVerification() throws {
        var wire = try cryptoKitWire(Data(repeating: 0x73, count: 9 * 1024 * 1024 + 3), bundle: bundle)
        wire[wire.count - 1] ^= 1
        let source = try file("bad-final-tag.dance", wire)
        let sentinel = Data("old-authoritative-output".utf8)
        let output = try file("verified.zip", sentinel)
        var observedPrivatePartial = false
        XCTAssertThrowsError(try codec.decrypt(container: source, destination: output, bundleId: bundle, shouldCancel: {
            XCTAssertEqual(try? Data(contentsOf: output), sentinel)
            if let temporary = try? self.temporaryFiles().first,
               let attributes = try? FileManager.default.attributesOfItem(atPath: temporary.path),
               let size = attributes[.size] as? NSNumber, size.uint64Value > 0 {
                observedPrivatePartial = true
                XCTAssertEqual((attributes[.posixPermissions] as? NSNumber)?.intValue, 0o600)
            }
            return false
        }))
        XCTAssertTrue(observedPrivatePartial)
        XCTAssertEqual(try Data(contentsOf: output), sentinel)
        XCTAssertTrue(try temporaryFiles().isEmpty)
    }

    func testDestinationEscapeAndSourceEqualsOutputFailWithoutWrites() throws {
        let source = try file("input.zip", Data([1, 2, 3]))
        let outside = root.deletingLastPathComponent().appendingPathComponent("outside-\(UUID().uuidString)").appendingPathComponent("out.dance")
        XCTAssertThrowsError(try codec.encrypt(zip: source, destination: outside, bundleId: bundle))
        XCTAssertFalse(FileManager.default.fileExists(atPath: outside.deletingLastPathComponent().path))
        XCTAssertThrowsError(try codec.encrypt(zip: source, destination: source, bundleId: bundle))
        XCTAssertEqual(try Data(contentsOf: source), Data([1, 2, 3]))
    }
}

/// Run separately in optimized configuration after small compatibility/authentication tests pass.
final class MdanceV1LargeFileTests: XCTestCase {
    func test184MiBStreamingRoundTripAndPeakMemoryGrowth() throws {
        let root = FileManager.default.temporaryDirectory.appendingPathComponent("mdance-large-test-\(UUID().uuidString)")
        try FileManager.default.createDirectory(at: root, withIntermediateDirectories: false)
        defer { try? FileManager.default.removeItem(at: root) }
        let source = root.appendingPathComponent("large.zip")
        let encrypted = root.appendingPathComponent("large.dance")
        let restored = root.appendingPathComponent("restored.zip")
        FileManager.default.createFile(atPath: source.path, contents: nil)
        let output = try FileHandle(forWritingTo: source)
        let block = Data((0..<65536).map { UInt8(truncatingIfNeeded: $0 * 31) })
        for _ in 0..<(184 * 16) { try output.write(contentsOf: block) }
        try output.close()
        func digest(_ url: URL) throws -> SHA256.Digest {
            let input = try FileHandle(forReadingFrom: url); defer { try? input.close() }
            var hash = SHA256()
            while true {
                let count: Int = try autoreleasepool {
                    let bytes = try input.read(upToCount: 65536) ?? Data()
                    hash.update(data: bytes); return bytes.count
                }
                if count == 0 { return hash.finalize() }
            }
        }
        var baseline = rusage(); XCTAssertEqual(getrusage(RUSAGE_SELF, &baseline), 0)
        let codec = MdanceV1Codec(privateRoot: root)
        try codec.encrypt(zip: source, destination: encrypted, bundleId: "com.midnightdancer.app")
        try codec.decrypt(container: encrypted, destination: restored, bundleId: "com.midnightdancer.app")
        XCTAssertEqual(try digest(source), try digest(restored))
        var after = rusage(); XCTAssertEqual(getrusage(RUSAGE_SELF, &after), 0)
        let growth = max(0, after.ru_maxrss - baseline.ru_maxrss)
        add(XCTAttachment(string: "184MiB streaming roundtrip peak resident growth bytes=\(growth)"))
        XCTAssertLessThan(growth, 64 * 1024 * 1024, "Full-payload memory allocation is forbidden")
    }
}
